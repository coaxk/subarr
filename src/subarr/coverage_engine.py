def _classify_audio_label(item: CoverageItem,
                          tautulli_hints: dict[str, str] | None = None,
                          user_verifications: dict[str, str] | None = None,
                          plex_hints: dict[str, str] | None = None,
                          whisper_verifications: dict[str, str] | None = None) -> None:
    """v1.1-O: cross-check audio_langs against Sonarr/Radarr originalLanguage.

    Three outcomes:
    - `audio_label_unknown` = ffprobe found NO language data at all (only "und",
      or empty) → no signal to trust; needs Whisper/review.
    - `audio_label_suspect` = original language is foreign (non-English) but
      every detected audio track is English → likely encoder defaulted to
      "eng" instead of tagging the real language. UI should warn before
      auto-suppressing this row from the queue.
    - Neither flag → either English-original content (expected), or audio
      data agrees with originalLanguage (good).

    Layer 2.5: if Tautulli reports the user picked a specific audio track
    in Plex for this title, that's authoritative — overrides ffprobe entirely
    for the audio_langs field and clears the suspect flag.

    The notes list (already populated by the title-fallback parser) is
    appended to so the UI can show the full evidence trail."""
    # Layer 0 (absolute): user verification beats everything.
    file_path = item.file_canonical_path
    if user_verifications and file_path and file_path in user_verifications:
        from .langs import normalize_lang
        confirmed = user_verifications[file_path]
        prior = [l for l in (item.audio_langs or []) if l and l.lower() not in ("", "und")]
        item.audio_langs = [confirmed]
        note = f"user-confirmed: {confirmed!r}"
        # #90 (C): a verification that disagrees with the file's tag is a
        # mismatch too ("you said X, tag said Y") — show the same dot.
        if prior and normalize_lang(confirmed) not in {normalize_lang(l) for l in prior}:
            note += f" — tags claimed {prior}"
            item.audio_label_whisper_mismatch = True
        item.audio_label_notes.append(note)
        item.audio_label_suspect = False
        item.audio_label_unknown = False
        item.audio_verified = True
        item.audio_source = "user"   # refined to whisper/auto in the post-pass
        return
    # Layer 1 (#90): Whisper-verified spoken language — subarr LISTENED to the
    # audio (robust multi-chunk detect), so it beats tag-derived Plex/Tautulli
    # picks (which inherit the file's mislabel) and the ffprobe tag; it sits
    # below an explicit user confirmation. DORMANT until verifications are
    # supplied (the on-demand trigger is slice 3) → no behaviour change yet.
    if whisper_verifications and file_path and file_path in whisper_verifications:
        from .langs import normalize_lang
        verified = (whisper_verifications[file_path] or "").lower()
        prior = [l for l in (item.audio_langs or []) if l and l.lower() not in ("", "und")]
        item.audio_langs = [verified]
        note = f"Whisper-verified audio = {verified!r} (heard the audio; overrides tags)"
        if prior and verified not in {normalize_lang(l) for l in prior}:
            note += f" — tags claimed {prior}, but the audio is {verified!r}"
            item.audio_label_whisper_mismatch = True
        item.audio_label_notes.append(note)
        item.audio_label_suspect = False
        item.audio_label_unknown = False
        # NOTE: deliberately NOT setting audio_verified — that flag is coupled to
        # USER-propagated-to-Sonarr semantics (drives the "awaiting Bazarr sync"
        # reason, and the frontend badge treats it as 'user'). A machine
        # detection signals via audio_source="whisper" instead, so it badges as
        # the Whisper ✓ tier and never claims a Sonarr propagation it didn't do.
        item.audio_source = "whisper"
        return
    title_lc = (item.title or "").strip().lower()
    if tautulli_hints and title_lc in tautulli_hints:
        plex_lang = tautulli_hints[title_lc]
        # User picked this in Plex → that's the actual audio. Authoritative.
        item.audio_langs = [plex_lang]
        item.audio_label_notes.append(
            f"Plex audio-track pick = {plex_lang!r} (overrides ffprobe)"
        )
        item.audio_label_suspect = False
        item.audio_label_unknown = False
        item.audio_source = "plex"
        return
    # Layer 2.6 (#12): the user's persisted per-show audio pick, read
    # directly from Plex metadata (selected audio stream). Below Tautulli-
    # live (which reflects the freshest in-session choice) but above the
    # ffprobe heuristics. Authoritative when present — same treatment as
    # the Tautulli pick, since both are the user's deliberate Plex choice.
    if plex_hints and title_lc in plex_hints:
        plex_lang = plex_hints[title_lc]
        item.audio_langs = [plex_lang]
        item.audio_label_notes.append(
            f"Plex selected-audio = {plex_lang!r} (per-show pick, overrides ffprobe)"
        )
        item.audio_label_suspect = False
        item.audio_label_unknown = False
        item.audio_source = "plex"
        return
    # [#118] Normalize audio tags to ISO-639-1 so the English-on-foreign-show
    # suspect check below catches eng/en-US, not just the bare 'en'/'eng' forms.
    from .langs import normalize_lang
    langs = [normalize_lang(l) or "und" for l in (item.audio_langs or [])]
    only_und = bool(langs) and all(l in ("", "und") for l in langs)
    no_data = not langs
    if only_und or no_data:
        item.audio_label_unknown = True
        item.audio_label_notes.append(
            "no audio language metadata — encoder didn't tag the stream"
        )
        return
    orig = (item.original_language or "").strip().lower()
    # Foreign originals: anything that isn't English.
    if orig and orig != "english":
        non_und = [l for l in langs if l not in ("", "und")]
        # Suspect when EVERY identified track is English on a foreign show.
        if non_und and all(l == "en" for l in non_und):  # langs are normalized
            item.audio_label_suspect = True
            item.audio_label_notes.append(
                f"originalLanguage={item.original_language!r} but audio tags "
                f"are all English ({non_und}) — likely encoder default"
            )
    # No higher-trust source fired (user/Plex returned early; suspect/unknown
    # set their flags) and we have a usable tag → the language came from the
    # file's ffprobe metadata only. Lowest trust — the UI badge shows it muted.
    if (item.audio_source is None and not item.audio_label_unknown
            and not item.audio_label_suspect
            and any(l not in ("", "und") for l in langs)):
        item.audio_source = "ffprobe"


class _SeriesIntentLookup(dict):
    """A {canonical_path: value} map that, on a miss, falls back to the
    longest series-intent prefix that the looked-up path starts with.

    #69: the coverage build loads verifications in BULK (get_all_as_lookup),
    which deliberately does NOT flatten series intents into one synthetic row
    per episode — that would be O(declared series x episodes) and would go
    stale the instant a new episode is added. Instead we keep the per-file
    rows as the fast exact-match layer and resolve series-intent inheritance
    lazily here. The net effect: a NEW episode under a declared-language
    series auto-resolves as verified during the coverage build, without any
    per-file re-verification — which is exactly the issue's intent.

    Per-file rows always win because dict exact-match short-circuits before
    the prefix fallback ever runs.
    """

    __slots__ = ("_intents",)

    def __init__(self, base: dict, intents: list[tuple[str, str]]):
        super().__init__(base)
        # Longest prefix first so the most specific declaration wins.
        self._intents = sorted(intents, key=lambda t: len(t[0]), reverse=True)

    def __bool__(self) -> bool:
        # Truthy if EITHER per-file rows OR series intents exist — callers
        # guard with `if user_verifications and ...`, and an intents-only
        # store (no per-file rows yet) must still be consulted (#69).
        return bool(len(self) or self._intents)

    def _match_intent(self, key) -> str | None:
        if not isinstance(key, str):
            return None
        for prefix, value in self._intents:
            if key.startswith(prefix):
                return value
        return None

    def __contains__(self, key) -> bool:  # type: ignore[override]
        if super().__contains__(key):
            return True
        return self._match_intent(key) is not None

    def __missing__(self, key):
        value = self._match_intent(key)
        if value is None:
            raise KeyError(key)
        return value

    def get(self, key, default=None):  # type: ignore[override]
        if super().__contains__(key):
            return super().__getitem__(key)
        value = self._match_intent(key)
        return value if value is not None else default


def _build_verification_lookup(audio_lang_store: Any):
    """Build the (user_verifications, verification_sources) pair the coverage
    build feeds to _classify_audio_label / _refine_audio_sources.

    Per-file verifications are the exact-match fast path; declared series
    intents are layered underneath via longest-prefix fallback (#69) so new
    episodes of a declared series inherit the language automatically.
    """
    if audio_lang_store is None:
        return {}, {}
    base_langs = audio_lang_store.get_all_as_lookup()
    base_sources = audio_lang_store.get_all_sources_as_lookup()
    intents = audio_lang_store.list_series_intents()
    lang_intents: list[tuple[str, str]] = [
        (i["series_prefix"], i["lang_code"]) for i in intents
    ]
    # Source string mirrors the per-path get() inheritance label so the UI
    # badge (via _refine_audio_sources -> "user") and any source-aware
    # consumer treats inherited rows as user-sourced.
    source_intents: list[tuple[str, str]] = [
        (i["series_prefix"], f"series_intent:{i.get('source', 'user')}")
        for i in intents
    ]
    user_verifications = _SeriesIntentLookup(base_langs, lang_intents)
    verification_sources = _SeriesIntentLookup(base_sources, source_intents)
    return user_verifications, verification_sources


def _refine_audio_sources(items: list, verification_sources: dict) -> None:
    """Post-pass: _classify set audio_source='user' for any store-verified hit;
    refine it to the ACTUAL verification source so the UI badge distinguishes
    user-verified from machine-detected (Whisper) audio. In place."""
    def _map(raw: str) -> str:
        r = raw.lower()
        if r.startswith("series_intent"):
            return "user"                  # inherited from a user's series declaration
        if "whisper" in r or "auto" in r:
            return "whisper"               # machine multi-chunk detect
        return "user"
    for it in items:
        s = verification_sources.get(it.file_canonical_path)
        if s:
            it.audio_source = _map(s)


def _score(
    item: CoverageItem,
    signals: dict[str, dict],
    *,
    now_playing_titles: set[str] | None = None,
    just_imported_eps: set[int] | None = None,
    just_imported_movies: set[int] | None = None,
    airing_soon_eps: set[int] | None = None,
    transcoding_titles: set[str] | None = None,
    ignore_forced_subtitles: bool = False,
) -> None:
    s = 0
    reasons: list[str] = []
    # v1.1-E: NOW PLAYING boost — strongest signal there is. If Plex is
    # streaming this title RIGHT NOW, queue it.
    title_lc = item.title.strip().lower()
    if now_playing_titles and title_lc in now_playing_titles:
        s += 2000
        reasons.append("PLAYING NOW")
        # v1.1-E++: even stronger if Plex is transcoding subs (CPU burn).
        if transcoding_titles and title_lc in transcoding_titles:
            s += 1000
            reasons.append("Plex transcoding subs — burn signal")
        # Mark for the UI chip
        item.now_playing = True
    # v1.1-I: just imported in last 24h — Sonarr/Radarr say a file just
    # landed; this is when watch likelihood peaks.
    if just_imported_eps and item.bazarr_episode_id in just_imported_eps:
        s += 800
        reasons.append("just imported (<24h)")
        item.just_imported = True
    elif just_imported_movies and item.bazarr_radarr_id in just_imported_movies:
        s += 800
        reasons.append("just imported (<24h)")
        item.just_imported = True
    # v1.1-H: airs within 48h — pre-warm the queue so subs are ready when
    # the episode hits disk.
    if airing_soon_eps and item.bazarr_episode_id in airing_soon_eps:
        s += 400
        reasons.append("airs within 48h")
        item.airing_soon = True
    sig = signals.get(title_lc)
    if sig:
        age_days = (time.time() - sig["last_played"]) / 86400.0 if sig["last_played"] else 9999
        if age_days <= 7:
            s += 1000
            reasons.append(f"watched in last 7d ({age_days:.0f}d)")
        elif age_days <= 30:
            s += 500
            reasons.append(f"watched in last 30d ({age_days:.0f}d)")
        if sig["plays_30d"] > 3:
            s += 200
            reasons.append(f"{sig['plays_30d']} plays in 30d")
    if item.original_language and item.original_language.lower() != "english":
        s += 100
        reasons.append(f"non-english ({item.original_language})")
    if item.monitored:
        s += 50
        reasons.append("monitored")
    if item.has_sub_on_disk:
        # Strong negative — disk has a sub, Bazarr's view is stale. Flip
        # suggest_bazarr_rescan too so the UI can offer the →Bazarr action
        # (the existing /api/bazarr/sync-disk endpoint).
        s -= 5000
        reasons.append("stale: disk already has .srt (Bazarr needs scan-disk)")
        item.suggest_bazarr_rescan = True
    # v1.1 hotfix + 2026-05-27 SDH collapse: SDH counts the same as a
    # clean English track for scoring purposes (an SDH track IS English).
    # Forced + commentary tracks remain partial (those genuinely aren't
    # full subs for the show).
    if item.embedded_en in {"EN", "EN(SDH)"}:
        s -= 3000
        label = "full English" if item.embedded_en == "EN" else "English SDH"
        reasons.append(f"embedded: {label} sub in file (Bazarr missed it)")
        item.suggest_bazarr_rescan = True
    elif item.embedded_en in {"EN(forced)", "EN(commentary)"}:
        s -= 500
        reasons.append(f"embedded: {item.embedded_en} — partial coverage")
        # #79: forced-only EN is only an ACTIONABLE gap if the connected
        # subgen will actually fill it (IGNORE_FORCED_SUBTITLES on). With the
        # cap off, subgen SKIPS forced-only files — so flag a distinct,
        # non-actionable state + reason instead of dangling an un-fillable gap.
        # The cap governs FORCED subs only; commentary tracks are untouched.
        if item.embedded_en == "EN(forced)" and not ignore_forced_subtitles:
            item.forced_only_subgen_will_skip = True
            reasons.append(
                "subgen will skip this (forced-only EN) — "
                "enable IGNORE_FORCED_SUBTITLES on subgen to transcribe it"
            )
    item.score = s
    item.score_reasons = reasons


