from .integrations.tautulli import TautulliClient

log = logging.getLogger(__name__)


@dataclass
class CoverageItem:
    media_type: str  # "episode" | "movie"
    title: str  # series title (episodes) / movie title
    episode_title: str | None = None
    episode_number: str | None = None  # "1x03"
    original_language: str | None = None
    monitored: bool | None = None
    tags: list[str] = field(default_factory=list)
    # Filesystem reality
    canonical_path: str | None = None  # relative to media_root, parent dir of the video
    has_sub_on_disk: bool = False  # any *.srt next to the video
    sub_files_seen: list[str] = field(default_factory=list)
    # Bazarr cross-reference
    bazarr_sonarr_id: int | None = None
    bazarr_radarr_id: int | None = None
    bazarr_episode_id: int | None = None
    missing_subtitles: list[str] = field(default_factory=list)
    # ffprobe-driven embedded reconciliation (v1.1 batch 1 hotfix)
    embedded_en: str | None = None   # 'EN' / 'EN(forced)' / 'EN(SDH)' / 'EN(commentary)' / None
    audio_langs: list[str] = field(default_factory=list)
    suggest_bazarr_rescan: bool = False
    # Resolved file path (file-level, not series-dir; populated when
    # Sonarr's episode_file is fetched during enrichment)
    file_canonical_path: str | None = None
    # v1.1-B: Sonarr/Radarr's authoritative "we don't have a file yet"
    # signal. When True, Bazarr is asking for subs on a file that hasn't
    # been imported — not actionable, suppress from default queue view.
    pending_download: bool = False
    # v1.1-E: Tautulli reports a Plex session streaming this title now.
    now_playing: bool = False
    # v1.1-I: Sonarr/Radarr imported the file in the last 24h.
    just_imported: bool = False
    # v1.1-H: Sonarr calendar says this airs in the next 48h.
    airing_soon: bool = False
    # v1.1-O: audio language data-quality flags.
    # `audio_label_suspect` = ffprobe says English audio but show is foreign
    #   per Sonarr/Radarr originalLanguage (the encoder probably defaulted
    #   to "eng" without setting the real language).
    # `audio_label_unknown` = ffprobe found no language tag at all ("und")
    #   AND we have no other evidence — needs review or Whisper detection.
    # `audio_label_notes` = human-readable evidence trail for the UI tooltip
    #   ("track 0: tag='eng' but title says 'fre'" / "originalLanguage=Spanish
    #   but audio_langs=['eng']" / etc).
    audio_label_suspect: bool = False
    audio_label_unknown: bool = False
    audio_label_notes: list[str] = field(default_factory=list)
    # v1.1.1 #219: synthetic row generated by the Bazarr-blind defense
    # because Bazarr's wanted view structurally excludes this file (foreign-
    # language series with file metadata claiming English audio). Frontend
    # uses this to render a distinct reason chip ("audio-mislabel-suspect")
    # and surface the upstream fix (set series Language Profile in Sonarr).
    bazarr_blind: bool = False
    # v1.1.1 #219 closer: True once the user verified the audio language
    # for this file. The classifier sets this when the user_verifications
    # lookup hits. Combined with bazarr_blind, the frontend renders a
    # distinct "awaiting Bazarr sync" reason (we propagated to Sonarr but
    # Bazarr's next sync hasn't fired yet) instead of the stale "mislabeled"
    # label that no longer reflects reality.
    audio_verified: bool = False
    # Scoring
    score: int = 0
    score_reasons: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "media_type": self.media_type,
            "title": self.title,
            "episode_title": self.episode_title,
            "episode_number": self.episode_number,
            "original_language": self.original_language,
            "monitored": self.monitored,
            "tags": self.tags,
            "canonical_path": self.canonical_path,
            "has_sub_on_disk": self.has_sub_on_disk,
            "sub_files_seen": self.sub_files_seen,
            "bazarr": {
                "sonarr_id": self.bazarr_sonarr_id,
                "radarr_id": self.bazarr_radarr_id,
                "episode_id": self.bazarr_episode_id,
                "missing_subtitles": self.missing_subtitles,
            },
            "embedded_en": self.embedded_en,
            "audio_langs": self.audio_langs,
            "suggest_bazarr_rescan": self.suggest_bazarr_rescan,
            "file_canonical_path": self.file_canonical_path,
            "pending_download": self.pending_download,
            "now_playing": self.now_playing,
            "just_imported": self.just_imported,
            "airing_soon": self.airing_soon,
            "audio_label_suspect": self.audio_label_suspect,
            "audio_label_unknown": self.audio_label_unknown,
            "audio_label_notes": self.audio_label_notes,
            "bazarr_blind": self.bazarr_blind,
            "audio_verified": self.audio_verified,
            "score": self.score,
            "score_reasons": self.score_reasons,
        }


@dataclass
class CoverageReport:
    generated_at: float
    sources: dict[str, dict[str, Any]]  # name -> {ok: bool, count?: int, error?: str}
    items: list[CoverageItem]

    def to_dict(self) -> dict[str, Any]:
        return {
            "generated_at": self.generated_at,
            "sources": self.sources,
            "items": [i.to_dict() for i in self.items],
            "totals": {
                "items": len(self.items),
                "episodes": sum(1 for i in self.items if i.media_type == "episode"),
                "movies": sum(1 for i in self.items if i.media_type == "movie"),
                "with_disk_sub": sum(1 for i in self.items if i.has_sub_on_disk),
                "embedded_full_en": sum(1 for i in self.items if i.embedded_en == "EN"),
                "suggest_bazarr_rescan": sum(1 for i in self.items if i.suggest_bazarr_rescan),
                # v1.1-B
                "pending_download": sum(1 for i in self.items if i.pending_download),
                "actionable": sum(1 for i in self.items if not i.pending_download),
            },
        }


