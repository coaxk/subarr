def _audio_metadata_looks_mislabeled(audio_langs: list[str] | None) -> bool:
    """The Bazarr-blind signature: file's audio metadata claims English
    OR is undetected, on a series Sonarr knows is foreign-language.
    `None` (no probe data) is treated as 'insufficient evidence'."""
    if audio_langs is None:
        return False
    # [#118] Normalize to ISO-639-1 so eng/en-US collapse to 'en' — otherwise a
    # region-tagged English track on a foreign show slips the mislabel check.
    from .langs import normalize_lang
    norm = [normalize_lang(l) or "und" for l in audio_langs]
    if not norm:
        # Empty audio_langs list = probe ran but found nothing → undetected,
        # which IS a bazarr-blind candidate (Bazarr also has nothing to go on).
        return True
    # Mislabeled signature: every detected track is English OR und.
    non_und = [l for l in norm if l not in ("", "und")]
    if not non_und:
        # All und → undetected, treat as candidate.
        return True
    return all(l == "en" for l in non_und)  # norm is ISO-639-1


def _is_en_sidecar_for(srt_path: str, file_stem: str) -> bool:
    """True if `srt_path` looks like an English sidecar for the video whose
    stem (filename minus extension) is `file_stem`. Tolerates Plex-style
    naming (<stem>.en.srt, <stem>.eng.srt) plus engine-suffix variants
    (<stem>.en.alass.srt, etc) since subsyncarr produces multiples."""
    name = srt_path.rsplit("/", 1)[-1]
    if not name.endswith(".srt"):
        return False
    base = name[:-4]
    if not base.startswith(file_stem):
        return False
    tail = base[len(file_stem):]
    if not tail.startswith("."):
        return False
    parts = [p for p in tail.split(".") if p]
    # Any token equal to en/eng marks it English.
    return any(p.lower() in ("en", "eng") for p in parts)
